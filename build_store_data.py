def match_portal(title, maker):
    n_title = normalize_text(title)
    
    # 1. 完全・包含マッチ
    for p in PORTAL_SEP_ITEMS:
        p_title = p.get("title", "")
        p_mercari = p.get("mercari", "")
        n_p = normalize_text(p_title)
        n_m = normalize_text(p_mercari)
        
        if n_title in n_p or n_p in n_title:
            return p
        if n_m and (n_title in n_m or n_m in n_title):
            return p

    # 2. キーワード重なりマッチ
    words = [w for w in re.split(r'[\s\-_・:：/／\(\)]+', title) if len(w) >= 2]
    best_p = None
    max_hits = 0
    for p in PORTAL_SEP_ITEMS:
        p_title = p.get("title", "")
        p_mercari = p.get("mercari", "")
        hits = 0
        for w in words:
            if w.lower() in p_title.lower() or w.lower() in p_mercari.lower():
                hits += 1
        if hits > max_hits and hits >= 2:
            max_hits = hits
            best_p = p
            
    if best_p:
        return best_p
        
    return None

