YAMATO_REF_MAP = {}
for _no, _mkr, _title, _date in YAMATOKORIYAMA_DATA:
    if _date != "未定" and "9月" in _date:
        _norm = normalize_text(_title)
        if _norm not in YAMATO_REF_MAP:
            YAMATO_REF_MAP[_norm] = _date

def get_yamato_ref_date(title):
    n = normalize_text(title)
    if n in YAMATO_REF_MAP:
        return YAMATO_REF_MAP[n]
    for y_n, y_d in YAMATO_REF_MAP.items():
        if n in y_n or y_n in n:
            return y_d
    return ""

def process_store_items(store_key, store_name, data_list):
    processed = []
    has_img_count = 0
    
    for no, maker, title, date in data_list:
        category = guess_category(title, maker)
        series = guess_series(title)
        is_undecided = (date == "未定")
        
        # 大和郡山店を参考にした納期補完
        ref_date = ""
        ref_day_num = 999
        if is_undecided:
            ref_date = get_yamato_ref_date(title)
            if ref_date:
                m = re.search(r'9月(\d+)日', ref_date)
                if m:
                    ref_day_num = int(m.group(1))
                    
        # 日付パース
        day_num = 999
        day_m = re.search(r'9月(\d+)日', date)
        if day_m:
            day_num = int(day_m.group(1))
        elif ref_day_num != 999:
            # 未定だが大和参考日がある場合、タイムライン用ソート番号に採用
            day_num = ref_day_num
            
        # 画像紐付け
        img_rel = ""
        matched_title = ""
        mercari_term = title
        
        # 1. カスタムマップ
        if title in CUSTOM_IMG_MAP:
            img_rel = CUSTOM_IMG_MAP[title]
        else:
            # 2. 自動マッチ
            m = match_portal(title, maker)
            if m:
                img_rel = m.get("img", "")
                matched_title = m.get("title", "")
                if m.get("mercari"):
                    mercari_term = m.get("mercari")
                    
        # 画像ファイル実在チェック
        final_img = ""
        if img_rel:
            img_basename = os.path.basename(img_rel)
            local_prize_img = os.path.join(CURRENT_DIR, "images", "prizes", img_basename)
            if os.path.exists(local_prize_img):
                final_img = f"images/prizes/{img_basename}"
                has_img_count += 1
            else:
                full_img = os.path.join(PORTAL_DIR, img_rel.replace("/", os.sep))
                if os.path.exists(full_img):
                    final_img = f"../1_Web公開・総合ポータル/{img_rel}"
                    has_img_count += 1
                
        processed.append({
            "id": f"{store_key}_{no}",
            "storeKey": store_key,
            "storeName": store_name,
            "no": no,
            "maker": maker,
            "title": title,
            "matchedTitle": matched_title,
            "date": date,
            "refDate": ref_date,
            "hasRefDate": bool(ref_date),
            "dayNum": day_num,
            "isUndecided": is_undecided,
            "category": category,
            "series": series,
            "image": final_img,
            "mercariTerm": mercari_term
        })
        
    print(f"[{store_name}] Total: {len(data_list)}, Image Matched: {has_img_count} ({has_img_count/len(data_list)*100:.1f}%)")
    return processed

